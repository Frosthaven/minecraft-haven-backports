"""Port methods that write data from Mojang's files: modded shelves, shelf displays, sounds, recipes, tags.

Split out of backport.py (each file stays under 500 lines); Port inherits them. Constants come from backport.
"""
import json
import os
import sys
from pathlib import Path

import models
import modshelves
import gear
from sources import asset, canon, old_format


B = None   # the backport module (set by backport.py: it holds the constants)


class DataPort:
    def mod_shelves(self, lang):
        mods = sys.argv[sys.argv.index("--mods") + 1] if "--mods" in sys.argv else os.environ.get("HAVEN_MODS")
        if not mods:
            sys.exit("modded shelves need --mods / HAVEN_MODS (the pack's mods folder)")
        self.modded_shelves, names, base = modshelves.run(self, B.RES, Path(mods))
        lang.update(names)
        print(f"modded shelves: {len(self.modded_shelves)}, art from: {base}")
        java = B.REPO / "src/main/java/dev/frosthaven/havenbackports/ModdedShelves.java"
        rows = ",\n".join(f'            new Wood("{sid}", "{ns}", "{planks}", {str(nether).lower()})'
                           for sid, ns, planks, nether in self.modded_shelves)
        java.write_text(f"""package dev.frosthaven.havenbackports;

import java.util.List;

/** Generated by tools/backport.py (tools/modshelves.py): shelves for the pack's modded woods. Do not edit by hand. */
final class ModdedShelves {{
    /** id, the wood's mod, that mod's planks (map color), nether wood (not flammable, like crimson and warped). */
    record Wood(String id, String mod, String planks, boolean nether) {{}}

    static final List<Wood> WOODS = List.of(
{rows});

    private ModdedShelves() {{}}
}}
""")

    def shelf_displays(self):
        patches, notes = models.vanilla_shelf_patches(self.jar, self.old)
        for path, data in patches.items():
            self.write(B.RES / "assets/minecraft/models" / f"{path}.json", data)
        self.n_shelf_patches = len(patches)
        if notes:
            print(f"on_shelf added to vanilla models 26.x also changed otherwise (1.21.1 content kept): {notes}")

    def sounds(self, lang, lang_new):
        mojang = json.loads(asset(self.objects, "minecraft/sounds.json"))
        out = {}
        events = [f"block.{sset}.{kind}" for sset, kinds in B.SOUND_SETS.items() for kind in kinds] + gear.SOUNDS
        for sset in B.DATA_SOUND_SETS:   # 26.x sound sets: the events their data names
            events += [e.split(":")[-1] for e in self.read(f"data/minecraft/block_sound_set/{sset}.json").values()]
        events += B.EXTRA_SOUNDS
        # sound files 1.21.1 ships with the same hash stay vanilla; so do music tracks 1.21.1 ships (26.x re-encoded
        # the same recordings smaller: the cave music's 11 shared tracks play 1.21.1's files, its 3 new ones ship here)
        old_index = Path.home() / ".local/share/PrismLauncher/assets/indexes/17.json"
        old_objects = json.loads(old_index.read_text())["objects"] if old_index.exists() else {}
        if True:
            for event in events:
                entry = json.loads(json.dumps(mojang[event]))
                for s in entry["sounds"]:
                    name = s["name"] if isinstance(s, dict) else s
                    path = name.split(":")[-1]
                    if isinstance(s, dict) and s.get("type") == "event":
                        if path not in events:
                            sys.exit(f"sound event {event} names event {path}, which is not ported")
                        s["name"] = f"{B.NS}:{path}"
                        continue
                    key = f"minecraft/sounds/{path}.ogg"
                    if key in old_objects and (old_objects[key]["hash"] == self.objects[key]["hash"] or path.startswith("music/")):
                        if isinstance(s, dict):
                            s["name"] = f"minecraft:{path}"
                        else:
                            entry["sounds"][entry["sounds"].index(s)] = f"minecraft:{path}"
                        continue
                    data = asset(self.objects, key)
                    out_file = B.RES / "assets" / B.NS / "sounds" / f"{path}.ogg"
                    out_file.parent.mkdir(parents=True, exist_ok=True)
                    out_file.write_bytes(data)
                    if isinstance(s, dict):
                        s["name"] = f"{B.NS}:{path}"
                    else:
                        entry["sounds"][entry["sounds"].index(s)] = f"{B.NS}:{path}"
                if "subtitle" in entry and entry["subtitle"] not in self.old_lang():
                    lang[entry["subtitle"]] = lang_new[entry["subtitle"]]   # Mojang's subtitle text, in our lang
                out[event] = entry
        self.write(B.RES / "assets" / B.NS / "sounds.json", out)

    def sound_id(self, event: str) -> str:
        """A sound event id: ours when this mod ships the event (1.21.1 lacks it), else vanilla."""
        name = event.split(":")[-1]
        return f"{B.NS}:{name}" if name in B.EXTRA_SOUNDS else event

    def exists_1211_id(self, vid, tag_file) -> bool:
        """A vanilla id a new tag may hold: what the tag's registry has in 1.21.1."""
        ns, path = vid.split(":")
        if ns != "minecraft":
            return False
        if "/tags/block/" in tag_file:
            return f"assets/minecraft/blockstates/{path}.json" in self.old_names
        if "/tags/entity_type/" in tag_file:
            return f"entity.minecraft.{path}" in self.old_lang()
        return self.exists_1211_item(vid)

    def old_lang(self):
        if not hasattr(self, "_old_lang"):
            self._old_lang = json.loads(self.old.read("assets/minecraft/lang/en_us.json"))
        return self._old_lang

    def recipes(self):
        self.old_recipe_keys = set()
        for n in self.old_names:
            if n.startswith("data/minecraft/recipe/") and n.endswith(".json"):
                self.old_recipe_keys.add(canon(old_format(json.loads(self.old.read(n)))))
        self.n_recipes = self.n_extra = 0
        for n in sorted(self.new_names):
            if not (n.startswith("data/minecraft/recipe/") and n.endswith(".json")):
                continue
            rid = n.split("/")[-1][:-5]
            raw = self.read(n)
            result = raw.get("result", {})
            result_id = (result.get("id") if isinstance(result, dict) else result) or ""
            ours = result_id.split(":")[-1] in B.OURS
            if rid in B.COVERED_BY_PACK:
                continue
            if not ours:
                if n in self.old_names or ":" not in result_id or not self.exists_1211_item(result_id):
                    continue
                if any(rid == x or (x.endswith("_") and rid.startswith(x)) for x in B.EXTRA_EXCLUDE):
                    continue
            r = self.recipe(raw)
            if r is None or self.equal_in_1211(r):
                continue
            self.write(B.RES / "data" / B.NS / "recipe" / f"{rid}.json", r)
            self.n_recipes += 1
            self.n_extra += 0 if ours else 1

    def tags(self):
        """Tags 1.21.1 has, or a written recipe uses, with our ids; plus the snapshot sub-tags they reference
        (slabs -> #wool_slabs, #concrete_slabs ...) when those hold ours."""
        tag_files = {n: self.read(n) for n in self.new_names if n.startswith("data/minecraft/tags/") and n.endswith(".json")}

        def ref_file(n, v):
            return n.split("/tags/", 1)[0] + "/tags/" + n.split("/tags/", 1)[1].split("/", 1)[0] + "/" + v[1:].split(":")[-1] + ".json"

        # code tags (our Java or our worldgen reads them) and every snapshot-only tag they reach: written whole, with
        # their vanilla members, since 1.21.1 has no such tag (blocks_motion -> #blocks_motion_no_leaves -> #ores ...)
        code, queue = set(), [n for n in tag_files if n.split("/")[-1][:-5] in B.CODE_TAGS]
        while queue:
            n = queue.pop()
            if n in code:
                continue
            code.add(n)
            for v in tag_files[n].get("values", []):
                if isinstance(v, str) and v.startswith("#") and ref_file(n, v) in tag_files and ref_file(n, v) not in self.old_names:
                    queue.append(ref_file(n, v))

        def own(n, seen=()):
            """Our values of a tag file, following #references into other snapshot tags (written as references)."""
            values = []
            for v in tag_files[n].get("values", []):
                if not isinstance(v, str):
                    continue
                if v.startswith("#") and n in code:
                    values.append(v)   # a tag only our Java reads keeps Mojang's references as they are
                    continue
                if v.startswith("#"):
                    ref = n.rsplit("/tags/", 1)[0] + "/tags/" + n.split("/tags/", 1)[1].split("/", 1)[0] + "/" + v[1:].split(":")[-1] + ".json"
                    if ref in tag_files and ref not in self.old_names and ref not in seen and holds_ours(ref, seen + (n,)):
                        values.append(v)
                    continue
                vid = self.id(v)
                recipe_tag = n.startswith("data/minecraft/tags/item/") and "minecraft:" + n.split("/", 4)[4][:-5] in self.recipe_tags
                # ours always; vanilla entries only in a tag a written recipe needs (metal_nuggets), never in a tag
                # 1.21.1 has or a sub-tag it would reach (that would change 1.21.1's own tag behaviour)
                code_tag = n in code and n not in self.old_names
                if vid.startswith(f"{B.NS}:") or ((recipe_tag or code_tag) and n not in self.old_names and self.exists_1211_id(vid, n)):
                    values.append(vid)
            return values

        def holds_ours(n, seen=()):
            for v in tag_files[n].get("values", []):
                if isinstance(v, str) and v.startswith("#"):
                    ref = n.split("/tags/", 1)[0] + "/tags/" + n.split("/tags/", 1)[1].split("/", 1)[0] + "/" + v[1:].split(":")[-1] + ".json"
                    # a tag 1.21.1 has is written on its own; own() never references it (it would dangle or
                    # widen 1.21.1's tags), so it does not count here either
                    if ref in tag_files and ref not in self.old_names and ref not in seen and holds_ours(ref, seen + (n,)):
                        return True
                elif isinstance(v, str) and self.id(v).startswith(f"{B.NS}:"):
                    return True
            return False

        def reach(n, seen=()):
            """Every plain id a snapshot tag file holds, through its references."""
            out = set()
            for v in tag_files.get(n, {}).get("values", []):
                v = v if isinstance(v, str) else v.get("id", "")
                if v.startswith("#"):
                    ref = n.split("/tags/", 1)[0] + "/tags/" + n.split("/tags/", 1)[1].split("/", 1)[0] + "/" + v[1:].split(":")[-1] + ".json"
                    if ref not in seen:
                        out |= reach(ref, seen + (n,))
                elif v:
                    out.add(self.id(v))
            return out

        # a family: a new snapshot tag that took over its vanilla members' place in 1.21.1's tags (B.FAMILY_TAGS)
        families = {f: reach(f) for f in tag_files if f not in self.old_names and f.split("/")[-1][:-5] in B.FAMILY_TAGS}

        def moved(n):
            """Ours where 26.x moved a vanilla entry of 1.21.1's tag n into a new family tag next to ours: 26.x
            dirt no longer lists moss_block, which went to the new #moss_blocks with pale_moss_block; 1.21.1 still
            checks #dirt (plants, saplings, trees), so pale moss joins 1.21.1's dirt as moss_block is there."""
            if n not in self.old_names:
                return []
            kind = n.split("/tags/", 1)[1].split("/", 1)[0]
            listed = {v for v in json.loads(self.old.read(n)).get("values", []) if isinstance(v, str) and not v.startswith("#")}
            gone = {self.id(v) for v in listed} - reach(n)
            out = []
            for f, members in families.items():
                if f.split("/tags/", 1)[1].split("/", 1)[0] == kind and gone & members:
                    out += sorted(m for m in members if m.startswith(f"{B.NS}:") and m not in out)
            if out:
                print(f"tag {n.split('/tags/', 1)[1]}: 26.x moved {sorted(gone)} into new family tags; adds {out}")
            return out

        wanted = [n for n in tag_files if n in self.old_names or n in code or
                  (n.startswith("data/minecraft/tags/item/") and "minecraft:" + n.split("/", 4)[4][:-5] in self.recipe_tags)]
        written, queue = set(), list(wanted)
        while queue:
            n = queue.pop()
            if n in written:
                continue
            values = own(n) + [v for v in moved(n) if v not in own(n)]
            if not values:
                continue
            written.add(n)
            self.write(B.RES / n, {"replace": False, "values": values})
            for v in values:
                if v.startswith("#"):
                    queue.append(n.split("/tags/", 1)[0] + "/tags/" + n.split("/tags/", 1)[1].split("/", 1)[0] + "/" + v[1:].split(":")[-1] + ".json")
        for kind in ("block", "item"):
            f = B.RES / f"data/minecraft/tags/{kind}/wooden_shelves.json"
            data = json.loads(f.read_text())
            data["values"] += [f"{B.NS}:{sid}" for sid, *_ in self.modded_shelves]
            self.write(f, data)
        nether = [f"{B.NS}:{sid}" for sid, _, _, n in self.modded_shelves if n]
        if nether:
            f = B.RES / "data/minecraft/tags/item/non_flammable_wood.json"
            data = json.loads(f.read_text())
            data["values"] += nether
            self.write(f, data)
        self.n_tags = len(written)
